// Regression tests for the v1.2 usability review's admin findings (A1-A17), in id order. The file name sorts it
// after the specs that expect an empty shop (fresh-install, clients): A10 and A11 must record a payment, and a
// paid invoice can be cancelled but not deleted.

function gcode(weightG: number, minutes: number, name: string): { name: string; mimeType: string; buffer: Buffer } {
  return {
    name,
    mimeType: "text/plain",
    buffer: Buffer.from(
      `; generated by PrusaSlicer 2.8.0 on 2026-01-01\n; filament used [g] = ${weightG}\n; estimated printing time (normal mode) = ${Math.floor(minutes / 60)}h ${minutes % 60}m 0s\nG28\n`,
    ),
  };
}

test.describe("A1: a missing-field link names the part it was written for", () => {
  test("a link clicked right after the part list changes still opens its own part (20 rounds)", async ({ page }) => {
    await page.goto("/admin/");
    await page.locator('.drop input[type="file"]').setInputFiles([gcode(10, 30, "bracket.gcode"), gcode(20, 60, "lid.gcode"), gcode(5, 10, "spacers.gcode")]);
    await expect(page.getByRole("tab")).toHaveCount(3);

    const weight = page.getByLabel(/Model weight/);
    const tab = (name: string) => page.getByRole("tab", { name: new RegExp(`^${name}`) });
    await tab("lid").click();
    await weight.fill("");
    const link = page.getByRole("group", { name: "Quote summary" }).getByRole("link", { name: /Price needs model weight \(lid\)/ });
    await expect(link).toBeVisible();

    for (let round = 0; round < 20; round++) {
      await tab("bracket").click();
      await expect(weight).toHaveValue("10");
      // Duplicating inserts a part at index 1, so the price answer on screen still describes "lid" as part 2
      // while the editor's part 2 is now the copy. The click lands inside the 350 ms debounce, well under 100 ms
      // after the edit (both clicks run in one page task).
      const elapsed = await page.evaluate(() => {
        const t0 = performance.now();
        document.querySelector<HTMLButtonElement>('button[aria-label^="Duplicate bracket"]')!.click();
        return new Promise<number>((resolve) =>
          queueMicrotask(() =>
            setTimeout(() => {
              const a = [...document.querySelectorAll<HTMLAnchorElement>('[aria-label="Quote summary"] a')].find((x) => /model weight/.test(x.textContent ?? ""));
              a?.click();
              resolve(performance.now() - t0);
            }, 20),
          ),
        );
      });
      expect(elapsed).toBeLessThan(100);

      await expect(tab("lid")).toHaveAttribute("aria-selected", "true");
      await expect(weight).toBeFocused();
      await expect(weight).toHaveValue("");

      // Typing into the focused field changes only the lid.
      await page.keyboard.type("7");
      await expect(weight).toHaveValue("7");
      for (const [name, g] of [["bracket", "10"], ["spacers", "5"]] as const) {
        await tab(name).first().click();
        await expect(weight).toHaveValue(g);
      }
      await tab("lid").click();
      await weight.fill("");

      // Remove the copy again so every round starts from the same three parts.
      await tab("bracket \\(copy\\)").click();
      await page.getByRole("button", { name: /^Remove bracket \(copy\)/ }).click();
      await page.getByRole("button", { name: /^Remove bracket \(copy\)\?/ }).click();
      await expect(page.getByRole("tab")).toHaveCount(3);
      await expect(link).toBeVisible();
    }
  });
});

