// Regression tests for the v1.2 usability review's admin findings (A1-A17), in id order. The file name sorts it
// after the specs that expect an empty shop (fresh-install, clients): A10 and A11 must record a payment, and a
// paid invoice can be cancelled but not deleted.

function gcode(weightG: number, minutes: number, name: string): { name: string; mimeType: string; buffer: Buffer } {
  return {
    name,
    mimeType: "text/plain",
    buffer: Buffer.from(
      `; generated by PrusaSlicer 2.8.0 on 2026-01-01\n; filament used [g] = ${weightG}\n; estimated printing time (normal mode) = ${Math.floor(minutes / 60)}h ${minutes % 60}m 0s\nG28\n`,
    ),
  };
}

test.describe("A1: a missing-field link names the part it was written for", () => {
  test("a link clicked right after the part list changes still opens its own part (20 rounds)", async ({ page }) => {
    await page.goto("/admin/");
    await page.locator('.drop input[type="file"]').setInputFiles([gcode(10, 30, "bracket.gcode"), gcode(20, 60, "lid.gcode"), gcode(5, 10, "spacers.gcode")]);
    await expect(page.getByRole("tab")).toHaveCount(3);

    const weight = page.getByLabel(/Model weight/);
    const tab = (name: string) => page.getByRole("tab", { name: new RegExp(`^${name}`) });
    await tab("lid").click();
    await weight.fill("");
    const link = page.getByRole("group", { name: "Quote summary" }).getByRole("link", { name: /Price needs model weight \(lid\)/ });
    await expect(link).toBeVisible();

    for (let round = 0; round < 20; round++) {
      await tab("bracket").click();
      await expect(weight).toHaveValue("10");
      // Duplicating inserts a part at index 1, so the price answer on screen still describes "lid" as part 2
      // while the editor's part 2 is now the copy. The click lands inside the 350 ms debounce, well under 100 ms
      // after the edit (both clicks run in one page task).
      const elapsed = await page.evaluate(() => {
        const t0 = performance.now();
        document.querySelector<HTMLButtonElement>('button[aria-label^="Duplicate bracket"]')!.click();
        return new Promise<number>((resolve) =>
          queueMicrotask(() =>
            setTimeout(() => {
              const a = [...document.querySelectorAll<HTMLAnchorElement>('[aria-label="Quote summary"] a')].find((x) => /model weight/.test(x.textContent ?? ""));
              a?.click();
              resolve(performance.now() - t0);
            }, 20),
          ),
        );
      });
      expect(elapsed).toBeLessThan(100);

      await expect(tab("lid")).toHaveAttribute("aria-selected", "true");
      await expect(weight).toBeFocused();
      await expect(weight).toHaveValue("");

      // Typing into the focused field changes only the lid.
      await page.keyboard.type("7");
      await expect(weight).toHaveValue("7");
      for (const [name, g] of [["bracket", "10"], ["spacers", "5"]] as const) {
        await tab(name).first().click();
        await expect(weight).toHaveValue(g);
      }
      await tab("lid").click();
      await weight.fill("");

      // Remove the copy again so every round starts from the same three parts.
      await tab("bracket \\(copy\\)").click();
      await page.getByRole("button", { name: /^Remove bracket \(copy\)/ }).click();
      await page.getByRole("button", { name: /^Remove bracket \(copy\)\?/ }).click();
      await expect(page.getByRole("tab")).toHaveCount(3);
      await expect(link).toBeVisible();
    }
  });
});

test.describe("A2: Add part moves focus to the new part", () => {
  test("Add part from a single part, and Duplicate, both land on the new part's name field", async ({ page }) => {
    await page.goto("/admin/");
    await page.getByRole("button", { name: "Add part" }).click();
    await expect(page.getByRole("tab")).toHaveCount(2);
    const name = page.getByLabel("Part name");
    await expect(name).toBeFocused();
    await expect(name).toHaveValue("Part 2");
    await page.getByRole("button", { name: "+ Add part" }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("tab")).toHaveCount(3);
    await expect(name).toBeFocused();
    await expect(name).toHaveValue("Part 3");
    await page.getByRole("button", { name: /^Duplicate Part 3/ }).click();
    await expect(page.getByRole("tab")).toHaveCount(4);
    await expect(name).toBeFocused();
    await expect(name).toHaveValue("Part 3 (copy)");
  });
});

test.describe("A3: weight and print time come before the Recent prints picker", () => {
  test("with Moonraker on, Model weight and Print time precede the picker in the DOM", async ({ page }) => {
    await page.goto("http://127.0.0.1:9199/admin/");
    const picker = page.getByLabel("Recent print (from Moonraker)");
    await expect(picker).toBeVisible();
    const weight = page.getByLabel(/Model weight/);
    const hours = page.getByLabel(/^Print time \(h/);
    const order = await page.evaluate(() => {
      const w = [...document.querySelectorAll("label")].find((l) => /^Model weight/.test(l.textContent ?? ""))!;
      const t = document.getElementById(document.querySelector<HTMLInputElement>('input[aria-label="Print time (hours)"]')!.id)!;
      const p = [...document.querySelectorAll("label")].find((l) => /Recent print/.test(l.textContent ?? ""))!;
      const follows = (a: Element, b: Element) => !!(a.compareDocumentPosition(b) & Node.DOCUMENT_POSITION_FOLLOWING);
      return { weight: follows(w, p), time: follows(t, p) };
    });
    expect(order).toEqual({ weight: true, time: true });
    await expect(weight).toBeVisible();
    await expect(hours).toBeVisible();
  });
});

test.describe("A4: a saved quote says so", () => {
  test("after Save the hint reads saved, the sidebar stays on New quote, and an edit brings back the warning", async ({ page, request }) => {
    await page.goto("/admin/");
    await fillCanonicalQuote(page);
    await page.getByLabel("Label for this quote").fill(`A4 ${Date.now()}`);
    await page.getByRole("button", { name: "Save quote" }).click();
    await expect(page.locator(".action-status")).toContainText("saved.");
    await expect(page.getByText("This quote is saved. Change anything, then press Update")).toBeVisible();
    await expect(page.getByText("Your changes aren't saved until you update it")).toHaveCount(0);
    await expect(navButton(page, "New quote")).toHaveAttribute("aria-current", "page");
    await expect(navButton(page, "Quotes")).not.toHaveAttribute("aria-current", "page");
    await page.getByLabel(/Model weight/).fill("51");
    await expect(page.getByText("Your changes aren't saved until you update it")).toBeVisible();
    // Leave no trace: the saved quote goes again.
    const id = new URL(page.url()).hash.replace("#/quote/", "");
    expect((await request.delete(`/admin/api/quotes/${id}`)).ok()).toBe(true);
  });
});

