<script lang="ts">
  import { tick } from "svelte";
  import { MediaQuery } from "svelte/reactivity";
  import { GUIDE_NAV, GUIDE_TASKS, GUIDE_TOPICS, SHORTCUTS, resolveGuideTopic } from "../lib/guideContent";
  import type { GuideImage } from "../lib/guideContent";
  import { parseInline } from "../lib/guideInline";
  import { splitHash } from "../lib/hashRoute";
  import Card from "./ui/Card.svelte";
  import PageHeader from "./ui/PageHeader.svelte";
  import dimensions from "../assets/guide/dimensions.json";

  // Guide images live under assets/guide and are imported only here, so Vite emits them with the admin bundle and
  // never with the public shop's entry. Each is generated by scripts/guide-shots.ts.
  const imageUrls = import.meta.glob("../assets/guide/*.webp", { eager: true, query: "?url", import: "default" }) as Record<string, string>;
  const sizes = dimensions as Record<string, { width: number; height: number }>;
  function imageSrc(key: string): string {
    return imageUrls[`../assets/guide/${key}.webp`] ?? "";
  }

  // The topic comes from the second fragment of the address ("#/guide#quote-a-print"), as in v1.1 deep links. An
  // unknown fragment opens the first task. Reading location.hash on mount covers a cold load and a link from
  // another page; the hashchange handler covers the topic list and in-guide links.
  let current = $state(resolveGuideTopic(splitHash(location.hash).fragment));
  let heading: HTMLElement | undefined = $state();
  async function onHashChange() {
    const { base, fragment } = splitHash(location.hash);
    if (base !== "#/guide") return;
    const next = resolveGuideTopic(fragment);
    if (next === current) return;
    current = next;
    navOpen = false;
    // The reader chose a new topic: move focus to its heading (WCAG 2.4.3) and show it from the top.
    await tick();
    heading?.focus({ preventScroll: true });
    document.getElementById("main")?.scrollTo(0, 0);
  }

  // At 900px and wider the topics are a rail beside the content, like the Settings sections. Below that they are a
  // collapsed "Choose a topic" disclosure above the content.
  const railQuery = new MediaQuery("min-width: 900px", true);
  const rail = $derived(railQuery.current);
  let navOpen = $state(false);

  const task = $derived(GUIDE_TASKS.find((t) => t.id === current));
  const concept = $derived(GUIDE_TOPICS.find((t) => t.id === current));
  const currentTitle = $derived(task?.title ?? concept?.title ?? "Keyboard shortcuts");
  function altFor(image: GuideImage): string {
    return image.alt;
  }
</script>

<svelte:window onhashchange={onHashChange} />

{#snippet inline(text: string)}
  {#each parseInline(text) as seg, i (i)}
    {#if seg.kind === "bold"}<strong>{seg.text}</strong>{:else if seg.kind === "code"}<code>{seg.text}</code>{:else if seg.kind === "link"}<a href={seg.href}>{seg.text}</a>{:else}{seg.text}{/if}
  {/each}
{/snippet}

<div class="page guide-page">
  <PageHeader title="Guide" />

  <div class="guide-layout">
    <nav class="topic-nav" aria-label="Guide topics">
      {#if !rail}
        <button type="button" class="topic-toggle" aria-expanded={navOpen} aria-controls="topic-list" onclick={() => (navOpen = !navOpen)}>
          Choose a topic: {currentTitle}
        </button>
      {/if}
      {#if rail || navOpen}
        <div id="topic-list" class="topic-groups">
          {#each GUIDE_NAV as group (group.group)}
            <h2 class="topic-group">{group.group}</h2>
            <ul class="topic-list">
              {#each group.items as item (item.id)}
                <li>
                  <a class="topic-link" href={`#/guide#${item.id}`} aria-current={item.id === current ? "page" : undefined}>{item.title}</a>
                </li>
              {/each}
            </ul>
          {/each}
        </div>
      {/if}
    </nav>

    <div class="topic-body">
      {#if task}
        <Card as="article" aria-labelledby="guide-heading">
          <h2 id="guide-heading" class="topic-title" tabindex="-1" bind:this={heading}>{task.title}</h2>
          <p class="summary">{task.summary}</p>
          <ol class="guide-steps">
            {#each task.steps as step, i (i)}
              <li>
                <p class="step-text">{@render inline(step.text)}</p>
                {#if step.image}
                  {@const dims = sizes[step.image.key]}
                  <img
                    class="shot"
                    src={imageSrc(step.image.key)}
                    alt={altFor(step.image)}
                    width={dims?.width}
                    height={dims?.height}
                    loading="lazy"
                    decoding="async"
                  />
                {/if}
              </li>
            {/each}
          </ol>
          {#if task.next}<p class="next">{@render inline(task.next)}</p>{/if}
        </Card>
      {:else if concept}
        <Card as="article" aria-labelledby="guide-heading">
          <h2 id="guide-heading" class="topic-title" tabindex="-1" bind:this={heading}>{concept.title}</h2>
          <p class="concept">{concept.body}</p>
        </Card>
      {:else}
        <Card as="article" aria-labelledby="guide-heading">
          <h2 id="guide-heading" class="topic-title" tabindex="-1" bind:this={heading}>Keyboard shortcuts</h2>
          <p>The sidebar footer lists the shortcuts that work on the page you are on. Shortcuts need Ctrl (or Cmd on a Mac), so typing letters never triggers them. Ctrl+K does nothing while you are typing in a text box.</p>
          <table>
            <thead><tr><th scope="col">Keys</th><th scope="col">What it does</th><th scope="col">Where</th></tr></thead>
            <tbody>
              {#each SHORTCUTS as sc (sc.keys)}
                <tr><th scope="row">{sc.keys}</th><td>{sc.action}</td><td>{sc.where}</td></tr>
              {/each}
            </tbody>
          </table>
        </Card>
      {/if}

      <p class="footnote">Next to many fields, a ? button opens a short explanation. Hover over it, focus it with the keyboard, or tap it.</p>
    </div>
  </div>
</div>

