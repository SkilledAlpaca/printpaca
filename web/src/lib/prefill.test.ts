import { beforeEach, describe, expect, it } from "vitest";
import { parseGcodeText, resolveGcode, type EffectiveConfig, type GcodeResult } from "./engine/index";
import { quote, toOrderInputs, type PartForm } from "./state.svelte";
import { splitSeconds } from "./gcodeTime";
import { applyResolvedPrefill, clearPrefillIfOwnedBy, isPrefillStale, prefill, prefillFor } from "./prefill.svelte";

function result(overrides: Partial<GcodeResult> = {}): GcodeResult {
  return { status: "ok", source: "reported-weight", ...overrides };
}

// `form` and `prefill` are module singletons; reset both so one test's apply can't leak into the next.
let part: PartForm;
beforeEach(() => {
  prefill.byPart = {};
  part = quote.parts[0]!;
  part.weightG = null;
  part.timeHours = null;
  part.timeMinutes = null;
  part.printerId = "printer-a";
  part.materialId = "material-a";
});

describe("applyResolvedPrefill", () => {
  it("rounds weightG to 2dp and writes it into the shared form", () => {
    applyResolvedPrefill(part, result({ weightG: 12.3456 }), "gcode", "part.gcode");
    expect(part.weightG).toBe(12.35);
  });

  it("splits timeSeconds into timeHours/timeMinutes via splitSeconds", () => {
    applyResolvedPrefill(part, result({ weightG: undefined, timeSeconds: 3725 }), "gcode", "part.gcode");
    expect(part.timeHours).toBe(1);
    expect(part.timeMinutes).toBe(2);
  });

  it("records source and label in the shared prefill state", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "moonraker", "job.gcode");
    expect(prefillFor(part)?.source).toBe("moonraker");
    expect(prefillFor(part)?.label).toBe("job.gcode");
  });

  it("snapshots the form values it just wrote, for later staleness comparison", () => {
    applyResolvedPrefill(part, result({ weightG: 10, timeSeconds: 600 }), "gcode", "part.gcode");
    expect(prefillFor(part)?.snapshot).toEqual({
      weightG: 10,
      timeHours: 0,
      timeMinutes: 10,
      printerId: "printer-a",
      materialId: "material-a",
    });
  });

  it("is a no-op (leaves the previous owner's record alone) when the result has neither weightG nor timeSeconds", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "first.gcode");
    const before = prefillFor(part);
    applyResolvedPrefill(part, { status: "not-found", source: "none" }, "moonraker", "second.gcode");
    expect(prefillFor(part)).toBe(before);
    expect(part.weightG).toBe(10);
  });

  it("a second apply from the other source overwrites both the form values and the ownership record", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "part.gcode");
    applyResolvedPrefill(part, result({ weightG: 25 }), "moonraker", "job.gcode");
    expect(part.weightG).toBe(25);
    expect(prefillFor(part)?.source).toBe("moonraker");
    expect(prefillFor(part)?.label).toBe("job.gcode");
  });
});

// The slicer's own cost estimate is parsed and shown but must never reach the QuoteInputs bag pricing is
// computed from (docs/formulas.md, slicer estimate): two fixtures differing only in a "; total filament
// cost = 99.99" comment must produce byte-identical QuoteInputs.
describe("costEstimate is parsed and displayed but never affects pricing", () => {
  const cfg = {
    currency: { symbol: "$", decimals: 2 },
    demoMode: false,
    materials: [],
    hardware: [],
    energy: { mode: "flat", flatRate: 0.15, tou: { peakRate: 0.3, offPeakRate: 0.1, defaultOffPeakFrac: 0.7 }, schedule: { defaultStartTime: "22:00", holidays: [], seasons: [] } },
  } as unknown as EffectiveConfig;

  const withCost = `; generated by PrusaSlicer 2.8.0 on 2026-01-01
; filament used [g] = 10.31
; total filament cost = 99.99
; estimated printing time (normal mode) = 1h 56m 0s
G28
`;
  const withoutCost = `; generated by PrusaSlicer 2.8.0 on 2026-01-01
; filament used [g] = 10.31
; estimated printing time (normal mode) = 1h 56m 0s
G28
`;

  it("parses/resolves costEstimate from the fixture that has it, and not from the one that doesn't (test setup sanity)", () => {
    const withMeta = parseGcodeText(withCost);
    const withoutMeta = parseGcodeText(withoutCost);
    expect(withMeta.costEstimate).toBeCloseTo(99.99, 5);
    expect(withoutMeta.costEstimate).toBeUndefined();
    // Everything else must match, so a QuoteInputs difference can't be a fixture mismatch.
    expect(withMeta.weightG).toBe(withoutMeta.weightG);
    expect(withMeta.timeSeconds).toBe(withoutMeta.timeSeconds);
  });

  it("produces an identical QuoteInputs bag through parse -> resolve -> applyResolvedPrefill -> toQuoteInputs, with or without the cost comment", () => {
    const withResolved = resolveGcode(parseGcodeText(withCost), 1.75, 1.24);
    applyResolvedPrefill(part, withResolved, "gcode", "with-cost.gcode");
    const withInputs = toOrderInputs(cfg).parts[0];

    part.weightG = null;
    part.timeHours = null;
    part.timeMinutes = null;

    const withoutResolved = resolveGcode(parseGcodeText(withoutCost), 1.75, 1.24);
    applyResolvedPrefill(part, withoutResolved, "gcode", "without-cost.gcode");
    const withoutInputs = toOrderInputs(cfg).parts[0];

    expect(withInputs).toEqual(withoutInputs);
  });
});

describe("per-part ownership", () => {
  it("keeps one record per part, so a drop onto one part never marks another stale", () => {
    const other = { ...part, id: "other", weightG: null as number | null };
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "a.gcode");
    applyResolvedPrefill(other, result({ weightG: 20 }), "moonraker", "b.gcode");
    expect(prefillFor(part)?.source).toBe("gcode");
    expect(prefillFor(other)?.source).toBe("moonraker");
    other.weightG = 21;
    expect(isPrefillStale(other)).toBe(true);
    expect(isPrefillStale(part)).toBe(false);
    clearPrefillIfOwnedBy(other, "moonraker");
    expect(prefillFor(other)).toBeNull();
    expect(prefillFor(part)).not.toBeNull();
  });
});

describe("isPrefillStale", () => {
  it("false when nothing has been applied yet", () => {
    expect(isPrefillStale(part)).toBe(false);
  });

  it("false immediately after an apply", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "part.gcode");
    expect(isPrefillStale(part)).toBe(false);
  });

  it("true once the applied weight is hand-edited", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "part.gcode");
    part.weightG = 11;
    expect(isPrefillStale(part)).toBe(true);
  });

  it("true once the printer selection changes (diameter a derived weight depended on)", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "part.gcode");
    part.printerId = "printer-b";
    expect(isPrefillStale(part)).toBe(true);
  });

  it("true once the material selection changes (density a derived weight depended on)", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "part.gcode");
    part.materialId = "material-b";
    expect(isPrefillStale(part)).toBe(true);
  });
});

describe("model source (STL / unsliced-3MF volume estimate)", () => {
  it("applies and records ownership the same as any other source", () => {
    applyResolvedPrefill(part, result({ weightG: 3.72 }), "model", "part.stl");
    expect(part.weightG).toBe(3.72);
    expect(prefillFor(part)?.source).toBe("model");
    expect(prefillFor(part)?.label).toBe("part.stl");
  });

  it("a fresh gcode apply supersedes a model estimate, and vice versa", () => {
    applyResolvedPrefill(part, result({ weightG: 3.72 }), "model", "part.stl");
    applyResolvedPrefill(part, result({ weightG: 12 }), "gcode", "part.gcode");
    expect(prefillFor(part)?.source).toBe("gcode");
    applyResolvedPrefill(part, result({ weightG: 4.1 }), "model", "part2.stl");
    expect(prefillFor(part)?.source).toBe("model");
    expect(part.weightG).toBe(4.1);
  });
});

describe("clearPrefillIfOwnedBy", () => {
  it("clears the record when the given source is the current owner", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "gcode", "part.gcode");
    clearPrefillIfOwnedBy(part, "gcode");
    expect(prefillFor(part)).toBeNull();
  });

  it("leaves the record alone when the given source is not the current owner", () => {
    applyResolvedPrefill(part, result({ weightG: 10 }), "moonraker", "job.gcode");
    clearPrefillIfOwnedBy(part, "gcode");
    expect(prefillFor(part)?.source).toBe("moonraker");
  });

  it("is a harmless no-op when there is no current record", () => {
    expect(() => clearPrefillIfOwnedBy(part, "gcode")).not.toThrow();
    expect(prefillFor(part)).toBeNull();
  });
});

describe("splitSeconds", () => {
  it("3595s rounds up to 1h 0m, never 0h 60m", () => {
    expect(splitSeconds(3595)).toEqual({ hours: 1, minutes: 0 });
  });

  it("7190s rounds up to 2h 0m, never 1h 60m", () => {
    expect(splitSeconds(7190)).toEqual({ hours: 2, minutes: 0 });
  });

  it("typical case: 3725s -> 1h 2m", () => {
    expect(splitSeconds(3725)).toEqual({ hours: 1, minutes: 2 });
  });

  it("zero seconds -> 0h 0m", () => {
    expect(splitSeconds(0)).toEqual({ hours: 0, minutes: 0 });
  });

  it("minutes never reach 60 for any input near an hour boundary", () => {
    for (let s = 3540; s <= 3660; s += 5) {
      const { minutes } = splitSeconds(s);
      expect(minutes).toBeLessThan(60);
      expect(minutes).toBeGreaterThanOrEqual(0);
    }
  });
});
