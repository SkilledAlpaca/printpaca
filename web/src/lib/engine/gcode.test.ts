import { describe, it, expect } from "vitest";
import { parseGcodeText, parseGcodeStream, resolveGcode } from "./gcode";

const cura = `;FLAVOR:Marlin
;TIME:6960
;Filament used: 3.456m
;Layer height: 0.2
;Generated with Cura_SteamEngine 5.7.0
G28
`;

const prusa = `; generated by PrusaSlicer 2.8.0 on 2026-01-01
; filament used [mm] = 3456.7
; filament used [g] = 10.31
; filament cost = 0.21
; estimated printing time (normal mode) = 1h 56m 0s
G28
`;

const orca = `; generated by OrcaSlicer 2.2.0
; filament used [g] = 12.34
; total filament used [g] = 15.99
; filament used [mm] = 4137.5
; model printing time: 1h 6m 12s; total estimated time: 1h 15m 32s
G28
`;

const snapmakerU1 = `; generated by OrcaSlicer 2.2.0
; filament used [g] = 12.34
; total filament used [g] = 15.99
; filament used [mm] = 4137.5
; model printing time: 1h 6m 12s
; total estimated time: 1h 15m 32s
G28
`;

const multiExtruder = `; generated by PrusaSlicer 2.8.0
; filament used [g] = 10.31, 4.20
; filament used [mm] = 3456.7, 1400.0
; estimated printing time (normal mode) = 2d 1h 2m 3s
`;

const noMeta = `G28\nG1 X10 Y10\nM104 S200\n`;

describe("parseGcodeText", () => {
  it("parses Cura headers (time seconds, length meters)", () => {
    const m = parseGcodeText(cura);
    expect(m.timeSeconds).toBe(6960);
    expect(m.lengthM).toBeCloseTo(3.456, 5);
    expect(m.weightG).toBeUndefined();
    expect(m.slicer).toContain("Cura");
  });
  it("parses PrusaSlicer headers (weight, mm length, cost, d/h/m/s time)", () => {
    const m = parseGcodeText(prusa);
    expect(m.weightG).toBeCloseTo(10.31, 5);
    expect(m.lengthM).toBeCloseTo(3.4567, 4);
    expect(m.costEstimate).toBeCloseTo(0.21, 5);
    expect(m.timeSeconds).toBe(1 * 3600 + 56 * 60);
    expect(m.slicer).toContain("PrusaSlicer");
  });
  it("rank-based selection: total beats model (weight and combined-line time)", () => {
    const m = parseGcodeText(orca);
    // "filament used [g]" (rank 1) comes first, but "total filament used [g]" (rank 2) wins
    expect(m.weightG).toBeCloseTo(15.99, 5);
    // Combined line: model time (rank 1) mid-line with total time (rank 2); capture bounds prevent
    // double-counting. Total wins: 3600 + 900 + 32 = 4532 s
    expect(m.timeSeconds).toBe(4532);
  });
  it("rank-based time selection: total beats model", () => {
    const m = parseGcodeText(snapmakerU1);
    // Model time (rank 1) appears before total time (rank 2); total wins: 4532 s
    expect(m.timeSeconds).toBe(4532);
    expect(m.weightG).toBeCloseTo(15.99, 5);
  });
  it("parses single-clause model time (no total clause present)", () => {
    const modelOnly = `; generated by OrcaSlicer 2.2.0
; model printing time: 1h 6m 12s
G28
`;
    const m = parseGcodeText(modelOnly);
    expect(m.timeSeconds).toBe(3972);
  });
  it("sums multi-extruder comma lists and parses day component", () => {
    const m = parseGcodeText(multiExtruder);
    expect(m.weightG).toBeCloseTo(14.51, 5);
    expect(m.lengthM).toBeCloseTo(4.8567, 4);
    expect(m.timeSeconds).toBe(2 * 86400 + 1 * 3600 + 2 * 60 + 3);
  });
  it("finds metadata anywhere in the file, not just the head", () => {
    const big = "G1 X0 Y0\n".repeat(20000) + ";TIME:120\n" + "G1 X1 Y1\n".repeat(20000);
    expect(parseGcodeText(big).timeSeconds).toBe(120);
  });
  it("returns empty meta when nothing is found", () => {
    expect(parseGcodeText(noMeta)).toStrictEqual({});
  });
  it("ignores decoy metadata in non-comment lines", () => {
    const withDecoy = "M117 ;Filament used: 99.9m\nG28\n";
    expect(parseGcodeText(withDecoy)).toStrictEqual({});
  });
  it("rejects malformed field names (underscore variant)", () => {
    const underscore = "; filament_cost = 24.99\nG28\n";
    expect(parseGcodeText(underscore)).toStrictEqual({});
  });
  it("rejects non-matching time patterns", () => {
    const wrongTime = ";TIME_ELAPSED:123.456\nG28\n";
    expect(parseGcodeText(wrongTime)).toStrictEqual({});
  });
  it("parses CRLF line endings", () => {
    const crlf = ";TIME:240\r\n;Filament used: 1.5m\r\nG28\r\n";
    const m = parseGcodeText(crlf);
    expect(m.timeSeconds).toBe(240);
    expect(m.lengthM).toBeCloseTo(1.5, 5);
  });
  it("parses Cura multi-extruder comma-separated lengths", () => {
    const curaMulti = ";Filament used: 1.234m, 5.678m\nG28\n";
    const m = parseGcodeText(curaMulti);
    expect(m.lengthM).toBeCloseTo(6.912, 4);
  });
  it("rejects malformed values (N/A) without recording", () => {
    const malformed = `; filament used [g] = N/A
G28
`;
    expect(parseGcodeText(malformed)).toStrictEqual({});
  });
  it("rejects negative values and accepts valid line after", () => {
    const negThenValid = `; filament used [g] = -5.0
; total filament used [g] = 10.0
G28
`;
    const m = parseGcodeText(negThenValid);
    expect(m.weightG).toBeCloseTo(10.0, 5);
  });
  it("bounds weight capture at semicolon: next clause's comma list does not leak in", () => {
    // Same bug class: an unbounded capture would sum the trailing ", 4.00" into the first clause (9.0).
    const combined = `; filament weight: 5.0; filament used [g] = 3.00, 4.00
G28
`;
    const m = parseGcodeText(combined);
    expect(m.weightG).toBeCloseTo(5.0, 5);
  });
  it("parses leading whitespace before semicolon", () => {
    const leadingSpace = `   ; filament used [g] = 10.31
G28
`;
    const m = parseGcodeText(leadingSpace);
    expect(m.weightG).toBeCloseTo(10.31, 5);
  });
});

describe("parseGcodeStream", () => {
  it("handles lines split across chunk boundaries", async () => {
    async function* chunks() {
      yield cura.slice(0, 20); // splits ";TIME:6960" mid-line
      yield cura.slice(20, 25);
      yield cura.slice(25);
    }
    const m = await parseGcodeStream(chunks());
    expect(m.timeSeconds).toBe(6960);
    expect(m.lengthM).toBeCloseTo(3.456, 5);
  });
});

describe("resolveGcode", () => {
  it("prefers reported weight", () => {
    const r = resolveGcode({ weightG: 10.31, lengthM: 3.4567 }, 1.75, 1.24);
    expect(r.source).toBe("reported-weight");
    expect(r.weightG).toBeCloseTo(10.31, 5);
    expect(r.status).toBe("ok");
  });
  it("derives weight from length when no reported weight", () => {
    const r = resolveGcode({ lengthM: 3.456 }, 1.75, 1.24);
    expect(r.source).toBe("derived-from-length");
    expect(r.weightG).toBeCloseTo(10.31, 1);
  });
  it("reports not-found when nothing usable", () => {
    const r = resolveGcode({}, 1.75, 1.24);
    expect(r.status).toBe("not-found");
    expect(r.source).toBe("none");
  });
  it("time alone is still ok, with source none", () => {
    const r = resolveGcode({ timeSeconds: 120 }, 1.75, 1.24);
    expect(r.status).toBe("ok");
    expect(r.source).toBe("none");
    expect(r.timeSeconds).toBe(120);
  });
  it("returns invalid-profile when lengthM found but profile invalid (diameterMm 0)", () => {
    const r = resolveGcode({ lengthM: 3.456 }, 0, 1.24);
    expect(r.status).toBe("invalid-profile");
    expect(r.source).toBe("none");
    expect(r.lengthM).toBe(3.456);
  });
  it("returns invalid-profile when lengthM found but profile invalid (density 0)", () => {
    const r = resolveGcode({ lengthM: 3.456 }, 1.75, 0);
    expect(r.status).toBe("invalid-profile");
    expect(r.source).toBe("none");
    expect(r.lengthM).toBe(3.456);
  });
  it("returns invalid-profile when lengthM found but profile invalid (diameterMm negative)", () => {
    const r = resolveGcode({ lengthM: 3.456 }, -1.75, 1.24);
    expect(r.status).toBe("invalid-profile");
    expect(r.source).toBe("none");
  });
  it("returns invalid-profile when lengthM found but profile invalid (density non-finite)", () => {
    const r = resolveGcode({ lengthM: 3.456 }, 1.75, NaN);
    expect(r.status).toBe("invalid-profile");
    expect(r.source).toBe("none");
  });
});

describe("hostile input", () => {
  it("parses a 1 MiB whitespace comment line in under 100 ms", () => {
    const hostile = `; generated by x${" ".repeat(1024 * 1024)}y\n`;
    const start = performance.now();
    const meta = parseGcodeText(`${hostile};TIME:60\n`);
    expect(performance.now() - start).toBeLessThan(100);
    expect(meta.timeSeconds).toBe(60);
  });
  it("streams a newline-free 1 MiB line in under 100 ms without losing later metadata", async () => {
    async function* chunks() {
      yield "; generated by x";
      for (let i = 0; i < 16; i++) yield " ".repeat(64 * 1024);
      yield "y\n;TIME:90\n";
    }
    const start = performance.now();
    const meta = await parseGcodeStream(chunks());
    expect(performance.now() - start).toBeLessThan(100);
    expect(meta.timeSeconds).toBe(90);
  });
  it("still extracts slicer names without the regex", () => {
    expect(parseGcodeText("; generated by PrusaSlicer 2.7.1 on 2024-01-01 at 10:00:00 UTC\n").slicer).toBe("PrusaSlicer 2.7.1");
    expect(parseGcodeText(";Generated with Cura_SteamEngine 5.7.0\n").slicer).toBe("Cura_SteamEngine 5.7.0");
    expect(parseGcodeText("; generated by Orca on\n").slicer).toBe("Orca on");
  });
});
