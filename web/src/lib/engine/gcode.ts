import { weightFromLength } from "./filament";

export interface RawGcodeMeta {
  weightG?: number;
  lengthM?: number;
  timeSeconds?: number;
  costEstimate?: number;
  slicer?: string;
}

export interface GcodeResult {
  status: "ok" | "not-found" | "invalid-profile";
  source: "reported-weight" | "derived-from-length" | "none";
  weightG?: number;
  lengthM?: number;
  timeSeconds?: number;
  costEstimate?: number;
  slicer?: string;
}

function sumList(raw: string): number | undefined {
  const parts = raw
    .split(",")
    .map((s) => Number.parseFloat(s))
    .filter((n) => Number.isFinite(n));
  if (parts.length === 0) return undefined;
  const sum = parts.reduce((a, b) => a + b, 0);
  return Number.isFinite(sum) && sum > 0 ? sum : undefined;
}

function parseDuration(raw: string): number | undefined {
  let seconds = 0;
  let matched = false;
  for (const m of raw.matchAll(/(\d+)\s*([dhms])/g)) {
    matched = true;
    const value = Number.parseInt(m[1]!, 10);
    const unit = m[2]!;
    seconds += value * (unit === "d" ? 86400 : unit === "h" ? 3600 : unit === "m" ? 60 : 1);
  }
  return matched && seconds > 0 ? seconds : undefined;
}

const WEIGHT_PATTERNS: Array<[pattern: RegExp, rank: number]> = [
  [/^;\s*total filament weight \[g\]\s*[:=]\s*([^;]+)/i, 2],
  [/^;\s*total filament used \[g\]\s*[:=]\s*([^;]+)/i, 2],
  [/^;\s*filament used \[g\]\s*=\s*([^;]+)/i, 1],
  [/^;\s*filament weight\s*[:=]\s*([^;]+)/i, 1],
];

const COST_PATTERNS: Array<[pattern: RegExp, rank: number]> = [
  [/^;\s*total filament cost\s*[:=]\s*([^;]+)/i, 2],
  [/^;\s*filament cost\s*[:=]\s*([^;]+)/i, 1],
];

const LENGTH_M_PATTERN = /^;\s*filament used:\s*(.+?)m\s*$/i;      // Cura: ";Filament used: 3.456m"
const LENGTH_MM_PATTERN = /^;\s*filament used \[mm\]\s*=\s*(.+)$/i;

/** Orca patterns are deliberately unanchored (no `^`) because those keys can appear mid-line; captures stop
 * at `;` to avoid double-counting clauses. */
const TIME_PATTERNS: Array<[pattern: RegExp, rank: number]> = [
  [/^;TIME:(\d+)/i, 2],                                                       // Cura, case-insensitive
  [/^;\s*estimated printing time \([^)]*\)\s*[:=]\s*([^;]+)/i, 2],            // Prusa rank 2
  [/;\s*total estimated time\s*[:=]\s*([^;]+)/i, 2],                          // Orca mid-line total
  [/;\s*model printing time\s*[:=]\s*([^;]+)/i, 1],                           // Orca mid-line model
];

/** Metadata comments are short. A longer comment line is slicer data (embedded thumbnails, config dumps) or
 * hostile input, and is skipped before any regex runs so a crafted line can't stall the parser. */
const MAX_COMMENT_LINE = 1024;

function isWs(ch: string | undefined): boolean {
  return ch === " " || ch === "\t" || ch === "\r" || ch === "\f" || ch === "\v";
}

/** Slicer name from "; generated by X [on date]" or ";Generated with X", with plain string handling (a regex
 * with `\s+` backtracking is quadratic on long whitespace runs). */
function parseSlicer(trimmed: string): string | undefined {
  const lower = trimmed.toLowerCase();
  let rest: string;
  if (lower.startsWith(";generated with") && isWs(trimmed[15])) {
    rest = trimmed.slice(15).trim();
  } else if (lower.startsWith(";")) {
    const body = trimmed.slice(1).trimStart();
    if (!body.toLowerCase().startsWith("generated by") || !isWs(body[12])) return undefined;
    rest = body.slice(12).trim();
    const restLower = rest.toLowerCase();
    // Cut at the first whitespace-delimited "on" that is followed by whitespace and more text.
    for (let i = restLower.indexOf("on"); i !== -1; i = restLower.indexOf("on", i + 1)) {
      if (i > 0 && isWs(rest[i - 1]) && isWs(rest[i + 2])) {
        rest = rest.slice(0, i).trimEnd();
        break;
      }
    }
  } else {
    return undefined;
  }
  return rest.length > 0 ? rest : undefined;
}

interface ParseState {
  weightG?: number;
  weightRank?: number;
  lengthM?: number;
  timeSeconds?: number;
  timeRank?: number;
  costEstimate?: number;
  costRank?: number;
  slicer?: string;
}

function parseLine(line: string, state: ParseState): void {
  const trimmed = line.trimStart();
  if (trimmed.length === 0 || trimmed[0] !== ";" || trimmed.length > MAX_COMMENT_LINE) return;

  if (state.slicer === undefined) {
    const slicer = parseSlicer(trimmed);
    if (slicer !== undefined) state.slicer = slicer;
  }

  if (state.timeRank === undefined || state.timeRank < 2) {
    for (let i = 0; i < TIME_PATTERNS.length; i++) {
      const entry = TIME_PATTERNS[i];
      if (!entry) continue;
      const [pattern, rank] = entry;
      const m = trimmed.match(pattern);
      if (m) {
        let value: number | undefined;
        if (i === 0) {
          value = Number.parseInt(m[1]!, 10);
          if (!Number.isFinite(value) || value <= 0) value = undefined;
        } else {
          value = parseDuration(m[1]!);
        }
        if (value !== undefined && (state.timeRank === undefined || rank > state.timeRank)) {
          state.timeSeconds = value;
          state.timeRank = rank;
        }
      }
    }
  }

  if (state.weightRank === undefined || state.weightRank < 2) {
    for (const [pattern, rank] of WEIGHT_PATTERNS) {
      const m = trimmed.match(pattern);
      if (m) {
        const value = sumList(m[1]!);
        if (value !== undefined && (state.weightRank === undefined || rank > state.weightRank)) {
          state.weightG = value;
          state.weightRank = rank;
        }
      }
    }
  }

  if (state.lengthM === undefined) {
    const cura = trimmed.match(LENGTH_M_PATTERN);
    if (cura) {
      const value = sumList(cura[1]!);
      if (value !== undefined) state.lengthM = value;
    } else {
      const mm = trimmed.match(LENGTH_MM_PATTERN);
      if (mm) {
        const value = sumList(mm[1]!);
        if (value !== undefined) state.lengthM = value / 1000;
      }
    }
  }

  if (state.costRank === undefined || state.costRank < 2) {
    for (const [pattern, rank] of COST_PATTERNS) {
      const m = trimmed.match(pattern);
      if (m) {
        const value = sumList(m[1]!);
        if (value !== undefined && (state.costRank === undefined || rank > state.costRank)) {
          state.costEstimate = value;
          state.costRank = rank;
        }
      }
    }
  }
}

function finishParse(state: ParseState): RawGcodeMeta {
  const result: RawGcodeMeta = {};
  if (state.weightG !== undefined) result.weightG = state.weightG;
  if (state.lengthM !== undefined) result.lengthM = state.lengthM;
  if (state.timeSeconds !== undefined) result.timeSeconds = state.timeSeconds;
  if (state.costEstimate !== undefined) result.costEstimate = state.costEstimate;
  if (state.slicer !== undefined) result.slicer = state.slicer;
  return result;
}

export function parseGcodeText(text: string): RawGcodeMeta {
  const state: ParseState = {};
  for (const line of text.split("\n")) parseLine(line.trimEnd(), state);
  return finishParse(state);
}

export async function parseGcodeStream(chunks: AsyncIterable<string>): Promise<RawGcodeMeta> {
  const state: ParseState = {};
  let buffer = "";
  // True while discarding the rest of a line already longer than MAX_COMMENT_LINE, so a newline-free stream
  // can't grow the buffer without bound or be rescanned on every chunk.
  let skipping = false;
  for await (const chunk of chunks) {
    let start = 0;
    for (;;) {
      const nl = chunk.indexOf("\n", start);
      if (nl === -1) {
        if (!skipping) {
          buffer += chunk.slice(start);
          if (buffer.length > MAX_COMMENT_LINE) { buffer = ""; skipping = true; }
        }
        break;
      }
      if (skipping) {
        skipping = false;
      } else {
        parseLine((buffer + chunk.slice(start, nl)).trimEnd(), state);
        buffer = "";
      }
      start = nl + 1;
    }
  }
  if (!skipping && buffer.length > 0) parseLine(buffer.trimEnd(), state);
  return finishParse(state);
}

export function resolveGcode(
  meta: RawGcodeMeta,
  diameterMm: number,
  density: number,
): GcodeResult {
  const common = {
    lengthM: meta.lengthM,
    timeSeconds: meta.timeSeconds,
    costEstimate: meta.costEstimate,
    slicer: meta.slicer,
  };
  if (meta.weightG !== undefined) {
    return { status: "ok", source: "reported-weight", weightG: meta.weightG, ...common };
  }
  if (meta.lengthM !== undefined) {
    if (!Number.isFinite(diameterMm) || diameterMm <= 0 || !Number.isFinite(density) || density <= 0) {
      return { status: "invalid-profile", source: "none", ...common };
    }
    return {
      status: "ok",
      source: "derived-from-length",
      weightG: weightFromLength(meta.lengthM, diameterMm, density),
      ...common,
    };
  }
  if (meta.timeSeconds !== undefined) {
    return { status: "ok", source: "none", ...common };
  }
  return { status: "not-found", source: "none", ...common };
}
