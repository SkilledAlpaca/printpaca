import { test, expect } from "@playwright/test";
import { historyRow, quotesRow, openMorePricing, openBreakdown, expandSummary } from "./helpers";

// Multi-part quote: drop three small synthetic G-code files at once (one part
// each, no real personal data), price them with per-part quantities and one
// override, then save, restore, print, and convert.

function gcode(weightG: number, minutes: number): { name: string; mimeType: string; buffer: Buffer } {
  return {
    name: "",
    mimeType: "text/plain",
    buffer: Buffer.from(
      `; generated by PrusaSlicer 2.8.0 on 2026-01-01\n; filament used [g] = ${weightG}\n; estimated printing time (normal mode) = ${Math.floor(minutes / 60)}h ${minutes % 60}m 0s\nG28\n`,
    ),
  };
}

const FILES = [
  { ...gcode(10, 30), name: "bracket.gcode" },
  { ...gcode(20, 60), name: "lid.gcode" },
  { ...gcode(5, 10), name: "spacers.gcode" },
];

function usd(cents: number): string {
  return `$${(cents / 100).toFixed(2)}`;
}

function cents(text: string): number {
  return Math.round(parseFloat(text.replace(/[^0-9.]/g, "")) * 100);
}

test("a three-part order: drop, price, save, restore, print, convert", async ({ page, request }) => {
  const label = `e2e-multipart-${Date.now()}`;
  await page.goto("/admin/");

  await page.locator('.drop input[type="file"]').setInputFiles(FILES);
  for (const name of ["bracket", "lid", "spacers"]) {
    await expect(page.getByRole("tab", { name: new RegExp(`^${name} ×`) })).toBeVisible();
  }
  await expect(page.getByRole("tab")).toHaveCount(3);

  const weight = page.getByLabel(/Model weight/);
  await page.getByRole("tab", { name: /^bracket ×/ }).click();
  await expect(weight).toHaveValue("10");
  await page.getByRole("tab", { name: /^lid ×/ }).click();
  await expect(weight).toHaveValue("20");
  await page.getByRole("tab", { name: /^spacers ×/ }).click();
  await expect(weight).toHaveValue("5");

  await page.getByLabel("Set a selling price").check();
  await openMorePricing(page);
  await page.getByLabel(/^Tax \(included in price\)/).fill("10");
  await page.getByLabel(/Shipping charged/).fill("5");

  await page.getByLabel(/^Quantity/).fill("20");
  await page.getByLabel(/Sale price override/).fill("0.75");
  await page.getByRole("tab", { name: /^bracket ×/ }).click();
  await page.getByLabel(/^Quantity/).fill("4");

  await openBreakdown(page);
  const orderTable = page.locator(".parts-table tbody tr");
  await expect(orderTable).toHaveCount(3);
  await expect(page.locator(".parts-table")).toContainText("$15.00"); // spacers: 20 x $0.75

  await page.getByLabel("Label for this quote").fill(label);
  await page.getByRole("button", { name: "Save quote" }).click();
  await expect(page.locator(".action-status")).toContainText(`"${label}" saved.`);

  const list = await (await request.get("/admin/api/quotes")).json();
  const saved = list.quotes.find((q: { label: string }) => q.label === label);
  expect(saved.partCount).toBe(3);
  expect(saved.quantity).toBe(1);
  expect(saved.valid).toBe(true);

  // Expected figures come from the editor's per-part "Price each" column: quantity x unit price per
  // part, plus the $5.00 shipping.
  const quantities = [4, 1, 20];
  const unitPrices: number[] = [];
  for (let i = 0; i < 3; i++) {
    unitPrices.push(cents(await orderTable.nth(i).locator("td").nth(4).innerText()));
  }
  expect(unitPrices[2]).toBe(75);
  const total = unitPrices.reduce((sum, unit, i) => sum + unit * quantities[i]!, 0) + 500;
  expect(saved.resolvedPriceCents + 500).toBe(total);

  await page.reload();
  // Opening over unsaved edits asks first; accept it.
  page.once("dialog", (d) => void d.accept());
  await historyRow(page, label).getByRole("button", { name: /^Open "/ }).click();
  await expect(page.getByRole("tab")).toHaveCount(3);
  await expect(page.getByLabel(/^Quantity/)).toHaveValue("4");
  await page.getByRole("tab", { name: /^spacers ×/ }).click();
  await expect(page.getByLabel(/^Quantity/)).toHaveValue("20");
  await expect(page.getByLabel(/Sale price override/)).toHaveValue("0.75");

  await page.evaluate(() => {
    window.print = () => {};
  });
  const printBtn = page.getByRole("button", { name: "Print client quote" });
  await expect(printBtn).toBeEnabled();
  await printBtn.click();
  const printView = page.locator("#print-view");
  await expect(printView).toBeVisible();
  const rows = printView.locator("tbody tr");
  await expect(rows).toHaveCount(5); // 3 parts + shipping + total
  await expect(rows.nth(0)).toContainText("bracket");
  await expect(rows.nth(1)).toContainText("lid");
  await expect(rows.nth(2)).toContainText("spacers");
  await expect(rows.nth(3)).toContainText("Shipping");
  await expect(rows.nth(4)).toContainText(usd(total));

  // Convert: one invoice line per part plus Shipping.
  await page.goto("/admin/#/quotes");
  const row = quotesRow(page, label);
  await expect(row).toContainText("3 parts");

  // Compute failure: Create invoice stays disabled (never a Shipping-only invoice).
  await page.route("**/api/quote/compute", (route) => route.fulfill({ status: 500, body: "{}" }));
  await row.getByRole("button", { name: `Convert to invoice: "${label}"` }).click();
  await expect(page.getByText("Couldn't price this order's parts")).toBeVisible();
  await expect(page.getByRole("button", { name: /^Create invoice/ })).toBeDisabled();
  await page.getByRole("button", { name: "Cancel" }).click();
  await page.unroute("**/api/quote/compute");
  await row.getByRole("button", { name: `Convert to invoice: "${label}"` }).click();
  const create = page.getByRole("button", { name: /^Create invoice/ });
  await expect(create).toBeEnabled();
  await expect(create).toContainText(usd(total));
  await create.click();
  await expect(page).toHaveURL(/#\/invoices/);

  const after = await (await request.get("/admin/api/quotes")).json();
  const converted = after.quotes.find((q: { label: string }) => q.label === label);
  expect(converted.invoicedAs).toBeTruthy();
  const invoice = await (await request.get(`/admin/api/invoices/${converted.invoicedAs}`)).json();
  expect(
    invoice.lines.map((l: { description: string; quantity: number; unitPriceCents: number }) => [l.description, l.quantity, l.unitPriceCents]),
  ).toEqual([
    [`${label} - bracket`, 4, unitPrices[0]],
    [`${label} - lid`, 1, unitPrices[1]],
    [`${label} - spacers`, 20, 75],
    ["Shipping", 1, 500],
  ]);
  expect(invoice.totalCents).toBe(total);
  // The Shipping line carries the shipping kind, which is what keeps it out of the taxed subtotal.
  expect(invoice.lines.map((l: { kind: string }) => l.kind)).toEqual(["item", "item", "item", "shipping"]);

  await request.delete(`/admin/api/quotes/${saved.id}`);
});

test("a single-part quote keeps the compact editor and an Add part action", async ({ page }) => {
  await page.goto("/admin/");
  await expect(page.getByRole("button", { name: "Add part" })).toBeVisible();
  await expect(page.getByLabel("Part name")).toHaveCount(0);
  await page.getByRole("button", { name: "Add part" }).click();
  await expect(page.getByRole("tab")).toHaveCount(2);
  await page.getByRole("button", { name: "Remove Part 2" }).click();
  await page.getByRole("button", { name: "Remove Part 2?" }).click();
  await expect(page.getByRole("button", { name: "Add part" })).toBeVisible();
  await expect(page.getByRole("tab")).toHaveCount(0);
});

test("a three-part order and the Quotes page fit a phone without sideways page scroll", async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const label = `e2e-phone-three-part-order-${Date.now()}`;
  await page.goto("/admin/");
  await page.locator('.drop input[type="file"]').setInputFiles(FILES);
  await page.getByLabel("Set a selling price").check();
  // Below 1100px the summary sits behind its pinned bar's Expand button.
  await expandSummary(page);
  await openBreakdown(page);
  await expect(page.locator(".parts-table tbody tr")).toHaveCount(3);
  const fits = () => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
  expect(await fits()).toBe(true);
  const overflow = await page.locator(".parts-table").evaluate((el) => el.scrollWidth - (el.parentElement?.clientWidth ?? 0));
  expect(overflow, "table overflow px").toBeLessThanOrEqual(0);

  await page.getByLabel("Label for this quote").fill(label);
  await page.getByRole("button", { name: "Save quote" }).click();
  await expect(page.locator(".action-status")).toContainText("saved.");

  await page.goto("/admin/#/quotes");
  await expect(quotesRow(page, label)).toBeVisible();
  expect(await fits()).toBe(true);

  const list = await (await request.get("/admin/api/quotes")).json();
  await request.delete(`/admin/api/quotes/${list.quotes.find((q: { label: string }) => q.label === label).id}`);
});
